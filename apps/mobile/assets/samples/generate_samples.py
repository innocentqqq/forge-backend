"""Regenerate the binary STL fixtures used by the ModelViewer dev screen.

All dimensions are in millimetres. Run from anywhere with:
    python3 apps/mobile/assets/samples/generate_samples.py
"""

from __future__ import annotations

import base64
import math
import struct
from pathlib import Path

Point = tuple[float, float, float]
Triangle = tuple[Point, Point, Point]

OUT_DIR = Path(__file__).resolve().parent


def cross(a: Point, b: Point) -> Point:
    return (
        a[1] * b[2] - a[2] * b[1],
        a[2] * b[0] - a[0] * b[2],
        a[0] * b[1] - a[1] * b[0],
    )


def subtract(a: Point, b: Point) -> Point:
    return (a[0] - b[0], a[1] - b[1], a[2] - b[2])


def normal_of(triangle: Triangle) -> Point:
    normal = cross(subtract(triangle[1], triangle[0]), subtract(triangle[2], triangle[0]))
    length = math.sqrt(sum(component * component for component in normal))
    if length == 0:
        raise ValueError("Degenerate triangle")
    return tuple(component / length for component in normal)  # type: ignore[return-value]


def quad(a: Point, b: Point, c: Point, d: Point) -> list[Triangle]:
    """Two triangles covering quad a-b-c-d (counter-clockwise when seen from outside)."""
    return [(a, b, c), (a, c, d)]


def box(x0: float, x1: float, y0: float, y1: float, z0: float, z1: float) -> list[Triangle]:
    """A closed axis-aligned cuboid with outward-facing triangles."""
    triangles: list[Triangle] = []
    # +Z / -Z
    triangles += quad((x0, y0, z1), (x1, y0, z1), (x1, y1, z1), (x0, y1, z1))
    triangles += quad((x1, y0, z0), (x0, y0, z0), (x0, y1, z0), (x1, y1, z0))
    # -Y / +Y
    triangles += quad((x0, y0, z0), (x1, y0, z0), (x1, y0, z1), (x0, y0, z1))
    triangles += quad((x1, y1, z0), (x0, y1, z0), (x0, y1, z1), (x1, y1, z1))
    # -X / +X
    triangles += quad((x0, y1, z0), (x0, y0, z0), (x0, y0, z1), (x0, y1, z1))
    triangles += quad((x1, y0, z0), (x1, y1, z0), (x1, y1, z1), (x1, y0, z1))
    return triangles


def frame_with_hole() -> list[Triangle]:
    """A 40 x 40 x 10 mm plate with a 20 x 20 mm square hole through Z."""
    x0, x1, y0, y1, z0, z1 = -20, 20, -20, 20, 0, 10
    xi0, xi1, yi0, yi1 = -10, 10, -10, 10
    triangles: list[Triangle] = []

    # Outer vertical walls (same winding as box()).
    triangles += quad((x0, y0, z0), (x1, y0, z0), (x1, y0, z1), (x0, y0, z1))
    triangles += quad((x1, y1, z0), (x0, y1, z0), (x0, y1, z1), (x1, y1, z1))
    triangles += quad((x0, y1, z0), (x0, y0, z0), (x0, y0, z1), (x0, y1, z1))
    triangles += quad((x1, y0, z0), (x1, y1, z0), (x1, y1, z1), (x1, y0, z1))

    # Inner vertical walls face into the hole.
    triangles += quad((xi0, yi0, z0), (xi0, yi1, z0), (xi0, yi1, z1), (xi0, yi0, z1))
    triangles += quad((xi1, yi1, z0), (xi1, yi0, z0), (xi1, yi0, z1), (xi1, yi1, z1))
    triangles += quad((xi0, yi0, z0), (xi0, yi0, z1), (xi1, yi0, z1), (xi1, yi0, z0))
    triangles += quad((xi1, yi1, z0), (xi1, yi1, z1), (xi0, yi1, z1), (xi0, yi1, z0))

    # Top and bottom rings: four quads each, leaving the hole empty.
    for z, reverse in ((z1, False), (z0, True)):
        strips = [
            ((x0, y0, z), (x1, y0, z), (x1, yi0, z), (x0, yi0, z)),
            ((x0, yi1, z), (x1, yi1, z), (x1, y1, z), (x0, y1, z)),
            ((x0, yi0, z), (xi0, yi0, z), (xi0, yi1, z), (x0, yi1, z)),
            ((xi1, yi0, z), (x1, yi0, z), (x1, yi1, z), (xi1, yi1, z)),
        ]
        for a, b, c, d in strips:
            triangles += quad(a, d, c, b) if reverse else quad(a, b, c, d)

    return triangles


def write_binary_stl(name: str, triangles: list[Triangle]) -> None:
    path = OUT_DIR / name
    with path.open("wb") as output:
        output.write(f"Forge sample: {name}".encode("ascii").ljust(80, b"\0"))
        output.write(struct.pack("<I", len(triangles)))
        for triangle in triangles:
            output.write(struct.pack("<12fH", *normal_of(triangle), *triangle[0], *triangle[1], *triangle[2], 0))
    print(f"{path.name}: {len(triangles)} triangles, {path.stat().st_size} bytes")


SAMPLES = (
    ("small-cube.stl", "Small cube", "smallCube"),
    ("large-box.stl", "Large box", "largeBox"),
    ("frame-with-hole.stl", "Frame with hole", "frameWithHole"),
)

MODULE_PATH = OUT_DIR.parent.parent / "components" / "ModelViewer" / "sample-data.ts"


def write_sample_data_module() -> None:
    """Metro has no .stl asset extension by default, so bundle base64 copies."""
    lines = [
        "// Generated by assets/samples/generate_samples.py — do not edit by hand.",
        "import type { ModelFormat } from './types';",
        "",
        "export interface SampleModel {",
        "  label: string;",
        "  format: ModelFormat;",
        "  url: string;",
        "}",
        "",
    ]
    for filename, label, identifier in SAMPLES:
        encoded = base64.b64encode((OUT_DIR / filename).read_bytes()).decode("ascii")
        lines.append(f"const {identifier} = 'data:model/stl;base64,{encoded}';")
    lines += [
        "",
        "export const SAMPLE_MODELS: SampleModel[] = [",
        *[f"  {{ label: {label!r}, format: 'stl', url: {identifier} }}," for _, label, identifier in SAMPLES],
        "];",
        "",
    ]
    MODULE_PATH.write_text("\n".join(lines), encoding="utf-8")
    print(f"Wrote {MODULE_PATH.name}")


if __name__ == "__main__":
    write_binary_stl("small-cube.stl", box(-5, 5, -5, 5, 0, 10))
    write_binary_stl("large-box.stl", box(-160, 160, -110, 110, 0, 300))
    write_binary_stl("frame-with-hole.stl", frame_with_hole())
    write_sample_data_module()
